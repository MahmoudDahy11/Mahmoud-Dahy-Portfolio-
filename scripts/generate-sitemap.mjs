/**
 * Generates `public/sitemap.xml` and `public/robots.txt` before a production build.
 *
 * Run with: `npm run sitemap`
 *
 * The SPA ships these two files from `public/`, where Vite copies them into the build
 * output. Regenerating them at build time (rather than committing static copies) is what
 * keeps the sitemap URL and the project detail entries current without a server:
 *
 *   - the site URL comes from `VITE_SITE_URL` in `.env`
 *   - project detail slugs come from the Supabase API, read as the public `anon` role
 *
 * If the API is unreachable the script still writes both files, with the static routes
 * only, so a build never fails because a crawler-facing file could not be refreshed.
 */

import { readFileSync, writeFileSync } from 'node:fs'

const ENV_FILE = new URL('../.env', import.meta.url)
const PUBLIC_DIR = new URL('../public/', import.meta.url)

/**
 * Reads the Vite environment file.
 *
 * A deliberate `dotenv`-free implementation: the file is flat `KEY=VALUE` lines, and pulling
 * in a dependency for one build step would be the kind of complexity `AGENTS.md` asks us to
 * avoid. Lines beginning with `#` and blank lines are ignored. Values already present in the
 * environment win, so a CI-supplied URL is never clobbered by the local `.env`.
 */
function loadEnvFile(path) {
  try {
    const text = readFileSync(path, 'utf8')

    for (const line of text.split('\n')) {
      const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)

      if (match && process.env[match[1]] === undefined) {
        process.env[match[1]] = match[2]
      }
    }
  } catch (error) {
    console.warn(`[sitemap] could not read ${path.name}: ${error.message}`)
  }
}

loadEnvFile(ENV_FILE)

const SUPABASE_URL = process.env.VITE_SUPABASE_URL ?? ''
const SUPABASE_ANON_KEY = process.env.VITE_SUPABASE_ANON_KEY ?? ''
const SITE_URL = (process.env.VITE_SITE_URL ?? 'http://localhost:5173').replace(/\/+$/, '')

/** The public routes that always exist, independent of the database. */
const staticRoutes = [
  '/',
  '/about',
  '/projects',
  '/experience',
  '/education',
  '/certificates',
  '/services',
  '/contact',
]

/**
 * Published project slugs, straight from the PostgREST endpoint.
 *
 * Uses the anon key and the public read path — the same data the site itself shows — so
 * the script needs no credential it does not already ship to every visitor.
 */
async function fetchProjectSlugs() {
  if (!SUPABASE_URL || !SUPABASE_ANON_KEY) {
    console.warn(
      '[sitemap] VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY are not set; using static routes only.',
    )
    return []
  }

  const url =
    `${SUPABASE_URL}/rest/v1/projects?select=slug,updated_at` +
    `&is_published=eq.true&order=sort_order.asc,created_at.asc`

  const response = await fetch(url, {
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      Accept: 'application/json',
    },
  })

  if (!response.ok) {
    throw new Error(`Supabase answered ${response.status} for the project slug query.`)
  }

  const rows = await response.json()
  return rows.map((row) => ({ slug: row.slug, lastModified: row.updated_at }))
}

/** Trims an ISO timestamp to a valid `lastmod` value, or `null`. */
function toLastModified(iso) {
  if (!iso) return null
  const date = new Date(iso)
  return Number.isNaN(date.getTime()) ? null : date.toISOString()
}

function escapeXml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

function urlFor(path) {
  return `${SITE_URL}${path === '/' ? '' : path}`
}

let slugs

try {
  slugs = await fetchProjectSlugs()
} catch (error) {
  // A crawler-facing file that could not be refreshed is worse than none, but it must
  // not take down the build. The static routes are always valid.
  console.warn(`[sitemap] project slugs unavailable (${error.message}); using static routes only.`)
  slugs = []
}

const entries = [
  ...staticRoutes.map((path) => ({ url: urlFor(path), lastmod: null })),
  ...slugs.map(({ slug, lastModified }) => ({
    url: urlFor(`/projects/${encodeURIComponent(slug)}`),
    lastmod: toLastModified(lastModified),
  })),
]

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...entries.map(
    (entry) =>
      `  <url><loc>${escapeXml(entry.url)}</loc>${
        entry.lastmod ? `<lastmod>${entry.lastmod}</lastmod>` : ''
      }</url>`,
  ),
  '</urlset>',
  '',
].join('\n')

const robots = [
  '# Generated by scripts/generate-sitemap.mjs — do not edit by hand.',
  '',
  '# Public portfolio pages may be crawled and indexed.',
  ...staticRoutes.map((path) => `Allow: ${path === '/' ? '/' : path}`),
  '',
  '# The admin dashboard is authentication-gated content management, not content.',
  'Disallow: /admin',
  '',
  `Sitemap: ${urlFor('/sitemap.xml')}`,
  '',
].join('\n')

writeFileSync(new URL('sitemap.xml', PUBLIC_DIR), xml)
writeFileSync(new URL('robots.txt', PUBLIC_DIR), robots)

console.log(
  `[sitemap] wrote ${staticRoutes.length} static routes and ${slugs.length} project pages to public/sitemap.xml`,
)
